"""Aggregate replication results into docs/research/results/replication.md (spec 01, Step 7).

    python scripts/aggregate.py [--stages=B1,B2] [--out=docs/research/results/replication.md]

Reads the run registry (final success, wall times, machines) and the run dirs' `eval.csv` /
`eval_only_*.csv` files. Cluster runs are read from `exp_logs_cluster/` (rsync of the cluster's
`exp_logs/`); local runs from their own run dir.

Only the block between the AUTO markers is (re)generated. Everything outside it (summary,
discrepancy list) is hand-written and kept as is. If the file does not exist, a skeleton is written.

Goal-reaching numbers: final-step `evaluation/overall_success × 100` of every `done` row in the
selected stages, mean ± std over seeds (std with ddof=1). If a (method, env, seed) appears in
several selected stages, the latest finished row wins.
"""
