# ---------------------------------------------------------------- data access

def local_run_dir(run_dir):
    """Where a run's files are on this machine: the run dir itself, or its mirror in exp_logs_cluster/."""
    if not run_dir:
        return None
    if os.path.isdir(run_dir):
        return run_dir
    if '/exp_logs/' in run_dir:
        mirrored = os.path.join(CLUSTER_MIRROR, run_dir.split('/exp_logs/', 1)[1])
        if os.path.isdir(mirrored):
            return mirrored
    return None


def parse_time(s):
    return datetime.fromisoformat(s) if s else None


def wall_minutes(row):
    start, end = parse_time(row['started_at']), parse_time(row['finished_at'])
    return (end - start).total_seconds() / 60 if start and end else None


def gpu_of(machine):
    if machine.startswith('dlc2gpu'):
        return 'L40S'
    if machine in ('workstation', 'cluster'):  # rows that only point at existing checkpoints
        return '—'
    return 'RTX 3090'


def final_runs(rows, stages):
    """{(method, env): {seed: row}} from done rows of the given stages; latest finish wins."""
    out = defaultdict(dict)
    for r in rows:
        if r['stage'] not in stages or r['status'] != 'done' or not r['final_success']:
            continue
        key, seed = (r['method'], r['env']), int(r['seed'])
        prev = out[key].get(seed)
        if prev is None or (r['finished_at'] or '') > (prev['finished_at'] or ''):
            out[key][seed] = r
    return out


def per_task_success(row):
    d = local_run_dir(row['run_dir'])
    if d is None or not os.path.exists(os.path.join(d, 'eval.csv')):
        return None
    last = logs.read_rows(os.path.join(d, 'eval.csv'))[-1]
    tasks, i = [], 1
    while f'evaluation/{i}_success' in last:
        tasks.append(float(last[f'evaluation/{i}_success']) * 100)
        i += 1
    return tasks


def eval_only_curve(run_dir, eval_seed=0):
    """{step: overall_success × 100} from eval_only_<step>_sd<seed>.csv (goal-reaching only)."""
    d = local_run_dir(run_dir)
    curve = {}
    if d is None:
        return curve
    for path in glob.glob(os.path.join(d, f'eval_only_*_sd{eval_seed}.csv')):
        m = re.fullmatch(rf'eval_only_(\d+)_sd{eval_seed}\.csv', os.path.basename(path))
        if not m:  # skips e.g. eval_only_<step>_regions_sd0.csv
            continue
        curve[int(m.group(1))] = float(logs.read_rows(path)[-1]['evaluation/overall_success']) * 100
    return curve


# ---------------------------------------------------------------- formatting

def fmt(x, nd=1):
    return '—' if x is None else f'{x:.{nd}f}'


def mean_std(values):
    v = np.asarray(values, dtype=float)
    return v.mean(), (v.std(ddof=1) if len(v) > 1 else float('nan'))


def md_table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(lines)


