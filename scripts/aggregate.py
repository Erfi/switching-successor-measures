"""Aggregate replication results into docs/research/results/replication.md (spec 01, Step 7).

    python scripts/aggregate.py [--stages=B1,B2] [--out=docs/research/results/replication.md]

Reads the run registry (final success, wall times, machines) and the run dirs' `eval.csv` /
`eval_only_*.csv` files. Cluster runs are read from `exp_logs_cluster/` (rsync of the cluster's
`exp_logs/`); local runs from their own run dir.

Only the block between the AUTO markers is (re)generated. Everything outside it (summary,
discrepancy list) is hand-written and kept as is. If the file does not exist, a skeleton is written.

Goal-reaching numbers: final-step `evaluation/overall_success × 100` of every `done` row in the
selected stages, mean ± std over seeds (std with ddof=1). If a (method, env, seed) appears in
several selected stages, the latest finished row wins.
"""
import argparse
import glob
import os
import re
import sys
from collections import defaultdict
from datetime import datetime

import numpy as np
from scipy import stats

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from scripts import logs, registry  # noqa: E402

AUTO_BEGIN = '<!-- BEGIN AUTO: generated by scripts/aggregate.py, do not edit by hand -->'
AUTO_END = '<!-- END AUTO -->'
DEFAULT_OUT = os.path.join(REPO_ROOT, 'docs', 'research', 'results', 'replication.md')
CLUSTER_MIRROR = os.path.join(REPO_ROOT, 'exp_logs_cluster')

METHOD_ORDER = ['hiql', 'icvf', 'onestep_fb', 'fb', 'fb_h', 'fbpis', 'fbpis_nonh']
METHOD_LABEL = {'hiql': 'HIQL', 'icvf': 'ICVF', 'onestep_fb': 'One-Step FB', 'fb': 'FB', 'fb_h': 'FB+πh',
                'fbpis': 'FBπS', 'fbpis_nonh': 'FBπS−πh'}
ENV_ORDER = ['medium', 'large', 'giant', 'teleport']

# Paper Table 6: success %, mean ± std over 5 seeds (spec 01, Step 7).
PAPER_TABLE6 = {
    'hiql': {'medium': (93, 1), 'large': (73, 6), 'giant': (5, 3), 'teleport': (42, 4)},
    'icvf': {'medium': (46, 37), 'large': (28, 3), 'giant': (0, 0), 'teleport': (23, 6)},
    'onestep_fb': {'medium': (35, 7), 'large': (23, 18), 'giant': (0, 0), 'teleport': (8, 2)},
    'fb': {'medium': (47, 1), 'large': (21, 5), 'giant': (0, 0), 'teleport': (25, 7)},
    'fb_h': {'medium': (50, 12), 'large': (20, 5), 'giant': (0, 0), 'teleport': (13, 7)},
    'fbpis': {'medium': (87, 6), 'large': (66, 9), 'giant': (1, 1), 'teleport': (40, 6)},
    'fbpis_nonh': {'medium': (70, 4), 'large': (37, 7), 'giant': (1, 1), 'teleport': (29, 4)},
}

# Spec acceptance criteria. (claim, kind, method A, method B, envs)
CLAIMS = [
    ('1. FBπS > FBπS−πh (hierarchy helps)', 'greater', 'fbpis', 'fbpis_nonh', ['medium', 'large']),
    ('2. FB+πh ≈ FB (small gains only)', 'close', 'fb_h', 'fb', ['medium', 'large']),
    ('3. FBπS−πh > FB (representation helps)', 'greater', 'fbpis_nonh', 'fb', ['medium', 'large']),
    ('4. FBπS within ~1 std of HIQL', 'close', 'fbpis', 'hiql', ['medium', 'large']),
]


# ---------------------------------------------------------------- data access

def local_run_dir(run_dir):
    """Where a run's files are on this machine: the run dir itself, or its mirror in exp_logs_cluster/."""
    if not run_dir:
        return None
    if os.path.isdir(run_dir):
        return run_dir
    if '/exp_logs/' in run_dir:
        mirrored = os.path.join(CLUSTER_MIRROR, run_dir.split('/exp_logs/', 1)[1])
        if os.path.isdir(mirrored):
            return mirrored
    return None


def parse_time(s):
    return datetime.fromisoformat(s) if s else None


def wall_minutes(row):
    start, end = parse_time(row['started_at']), parse_time(row['finished_at'])
    return (end - start).total_seconds() / 60 if start and end else None


def gpu_of(machine):
    if machine.startswith('dlc2gpu'):
        return 'L40S'
    if machine in ('workstation', 'cluster'):  # rows that only point at existing checkpoints
        return '—'
    return 'RTX 3090'


def final_runs(rows, stages):
    """{(method, env): {seed: row}} from done rows of the given stages; latest finish wins."""
    out = defaultdict(dict)
    for r in rows:
        if r['stage'] not in stages or r['status'] != 'done' or not r['final_success']:
            continue
        key, seed = (r['method'], r['env']), int(r['seed'])
        prev = out[key].get(seed)
        if prev is None or (r['finished_at'] or '') > (prev['finished_at'] or ''):
            out[key][seed] = r
    return out


def per_task_success(row):
    d = local_run_dir(row['run_dir'])
    if d is None or not os.path.exists(os.path.join(d, 'eval.csv')):
        return None
    last = logs.read_rows(os.path.join(d, 'eval.csv'))[-1]
    tasks, i = [], 1
    while f'evaluation/{i}_success' in last:
        tasks.append(float(last[f'evaluation/{i}_success']) * 100)
        i += 1
    return tasks


def eval_only_curve(run_dir, eval_seed=0):
    """{step: overall_success × 100} from eval_only_<step>_sd<seed>.csv (goal-reaching only)."""
    d = local_run_dir(run_dir)
    curve = {}
    if d is None:
        return curve
    for path in glob.glob(os.path.join(d, f'eval_only_*_sd{eval_seed}.csv')):
        m = re.fullmatch(rf'eval_only_(\d+)_sd{eval_seed}\.csv', os.path.basename(path))
        if not m:  # skips e.g. eval_only_<step>_regions_sd0.csv
            continue
        curve[int(m.group(1))] = float(logs.read_rows(path)[-1]['evaluation/overall_success']) * 100
    return curve


# ---------------------------------------------------------------- formatting

def fmt(x, nd=1):
    return '—' if x is None else f'{x:.{nd}f}'


def mean_std(values):
    v = np.asarray(values, dtype=float)
    return v.mean(), (v.std(ddof=1) if len(v) > 1 else float('nan'))


def md_table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(lines)


# ---------------------------------------------------------------- sections

def goal_reaching_section(runs, stages):
    out = [f'### 1. Goal-reaching (success %, final step, stages {", ".join(stages)})', '',
           'Mean ± std over seeds (ddof=1). Flag: |ours − paper| > 2 × paper std + 5 (spec acceptance '
           'criteria). Paper: Table 6, 5 seeds.', '']
    rows, missing = [], []
    for env in ENV_ORDER:
        for m in METHOD_ORDER:
            seeds = runs.get((m, env), {})
            p_mean, p_std = PAPER_TABLE6[m][env]
            if not seeds:
                missing.append(f'{METHOD_LABEL[m]} {env}')
                continue
            vals = [float(seeds[s]['final_success']) for s in sorted(seeds)]
            mu, sd = mean_std(vals)
            delta, thr = mu - p_mean, 2 * p_std + 5
            rows.append([env, METHOD_LABEL[m], len(vals), ' / '.join(f'{v:.1f}' for v in vals),
                         f'{mu:.1f} ± {fmt(sd)}', f'{p_mean} ± {p_std}', f'{delta:+.1f}', thr,
                         '**FLAG**' if abs(delta) > thr else 'no'])
    out.append(md_table(['Env', 'Method', 'n', 'Per seed (sorted by seed)', 'Ours', 'Paper', 'Δ', 'Thr', 'Flag'],
                        rows))
    if missing:
        out += ['', 'Not run yet: ' + ', '.join(missing) + '.']

    # Per-task means.
    out += ['', 'Per-task success, mean over seeds (tasks 1–5):', '']
    trows = []
    for env in ENV_ORDER:
        for m in METHOD_ORDER:
            seeds = runs.get((m, env), {})
            tasks = [per_task_success(seeds[s]) for s in sorted(seeds)]
            tasks = [t for t in tasks if t]
            if not tasks:
                continue
            means = np.mean(np.array(tasks), axis=0)
            trows.append([env, METHOD_LABEL[m], len(tasks)] + [f'{x:.0f}' for x in means])
    n_tasks = max((len(r) - 3 for r in trows), default=5)
    out.append(md_table(['Env', 'Method', 'n'] + [f'T{i}' for i in range(1, n_tasks + 1)], trows))
    return '\n'.join(out)


def claims_section(runs):
    out = ['### Qualitative claims', '',
           'Rules used here: "A > B" **holds** if Δ > 0 and a one-sided Welch t-test gives p < 0.05, '
           '**marginal** if Δ > 0 otherwise, **fails** if Δ ≤ 0. "A ≈ B" / "within ~1 std" **holds** if '
           '|Δ| ≤ the larger of the two stds. These thresholds are our reading of the spec, not the paper\'s.', '']
    rows = []
    for claim, kind, a, b, envs in CLAIMS:
        for env in envs:
            va = [float(r['final_success']) for r in runs.get((a, env), {}).values()]
            vb = [float(r['final_success']) for r in runs.get((b, env), {}).values()]
            pa, pb = PAPER_TABLE6[a][env][0], PAPER_TABLE6[b][env][0]
            if len(va) < 2 or len(vb) < 2:
                rows.append([claim, env, '—', '—', f'{pa - pb:+d}', 'not testable (too few seeds)'])
                continue
            (ma, sa), (mb, sb) = mean_std(va), mean_std(vb)
            delta = ma - mb
            if kind == 'greater':
                p = stats.ttest_ind(va, vb, equal_var=False, alternative='greater').pvalue
                verdict = 'holds' if delta > 0 and p < 0.05 else ('marginal' if delta > 0 else 'fails')
                detail = f'p = {p:.3f}'
            else:
                tol = max(sa, sb)
                verdict = 'holds' if abs(delta) <= tol else 'fails'
                detail = f'tol = {tol:.1f}'
            rows.append([claim, env, f'{ma:.1f} vs {mb:.1f}', f'{delta:+.1f} ({detail})', f'{pa - pb:+d}',
                         f'**{verdict}**'])
    out.append(md_table(['Claim', 'Env', 'Ours (A vs B)', 'Δ ours', 'Δ paper', 'Verdict'], rows))
    return '\n'.join(out)


def general_reward_section(rows):
    have = [r for r in rows if r['status'] == 'done' and r['env'] in ('large', 'giant')
            and r['method'] not in ('hiql',) and r['stage'] in ('B1', 'B2', 'C_opt', 'D')]
    regions = 0
    for r in have:
        d = local_run_dir(r['run_dir'])
        if d and glob.glob(os.path.join(d, 'eval_only_*_regions_sd*.csv')):
            regions += 1
    return '\n'.join([
        '### 2. General rewards (Table 7)', '',
        f'Not computed yet: {regions} run(s) have `eval_only_*_regions_*.csv` files. Needs '
        '`scripts/eval_checkpoint.py --complex_task_name=regions` on the Large and Giant checkpoints '
        '(Giant = Stage D, not run), then IQM with stratified-bootstrap CIs (App. C.5).'])


def learning_curves_section(rows):
    """Mean eval-only success per (stage group, method, env) over the runs that have checkpoints evaluated."""
    groups = defaultdict(list)  # (method, env, label) -> [curve]
    for r in rows:
        if r['status'] != 'done' or r['stage'].startswith('smoke') or r['stage'].startswith('I2'):
            continue
        curve = eval_only_curve(r['run_dir'])
        if len(curve) < 2:
            continue
        label = f'{gpu_of(r["machine"])}, {r["stage"]}'
        groups[(r['method'], r['env'], label)].append((int(r['seed']), curve))
    out = ['### 3. Learning curves (eval-only, 50 episodes × 5 tasks, eval seed 0)', '',
           'From `scripts/eval_checkpoint.py` on the 100k checkpoints. Hierarchical runs are 500k steps on '
           'top of their 1M base. Only runs whose checkpoints were evaluated are shown.', '']
    if not groups:
        return '\n'.join(out + ['None yet.'])
    for (m, env, label), entries in sorted(groups.items(), key=lambda kv: (ENV_ORDER.index(kv[0][1]),
                                                                            METHOD_ORDER.index(kv[0][0]))):
        steps = sorted(set().union(*[c.keys() for _, c in entries]))
        header = ['Seed'] + [f'{s // 1000}k' for s in steps]
        trows = [[s] + [fmt(c.get(st)) for st in steps] for s, c in sorted(entries)]
        if len(entries) > 1:
            trows.append(['**mean**'] + [fmt(np.mean([c[st] for _, c in entries if st in c])) for st in steps])
        out += [f'**{METHOD_LABEL[m]}, {env}** ({label})', '', md_table(header, trows), '']
    return '\n'.join(out).rstrip()


def inventory_section(rows):
    out = ['### 4. Run inventory', '']
    by_stage = defaultdict(lambda: defaultdict(int))
    for r in rows:
        by_stage[r['stage']][r['status']] += 1
    statuses = ['done', 'failed', 'running', 'queued', 'planned']
    out.append(md_table(['Stage', 'Rows'] + statuses,
                        [[s, sum(c.values())] + [c.get(k, 0) for k in statuses] for s, c in by_stage.items()]))

    times = defaultdict(list)
    gpu_h = defaultdict(float)
    for r in rows:
        w = wall_minutes(r)
        if r['status'] != 'done' or w is None or r['stage'].startswith('smoke'):
            continue
        times[(r['method'], r['env'], gpu_of(r['machine']))].append(w)
        gpu_h[r['stage']] += w / 60
    out += ['', 'Wall time per run (min, done rows, excl. smoke; includes the 2 evaluations):', '']
    trows = [[METHOD_LABEL[m], env, gpu, len(v), f'{min(v):.0f}', f'{np.median(v):.0f}', f'{max(v):.0f}']
             for (m, env, gpu), v in sorted(times.items(), key=lambda kv: (ENV_ORDER.index(kv[0][1]),
                                                                           METHOD_ORDER.index(kv[0][0]), kv[0][2]))]
    out.append(md_table(['Method', 'Env', 'GPU', 'n', 'min', 'median', 'max'], trows))
    out += ['', 'GPU-hours per stage (done rows): ' + ', '.join(f'{s} {h:.1f}' for s, h in gpu_h.items()) + '.']

    bad = [r for r in rows if r['status'] == 'failed' or re.search(r'-r\d+$', r['run_id'])]
    out += ['', 'Failed or re-run rows:', '']
    if bad:
        out.append(md_table(['Run', 'Status', 'Notes'],
                            [[r['run_id'], r['status'], (r['notes'] or '').replace('|', '/')[:120]] for r in bad]))
    else:
        out.append('None.')
    return '\n'.join(out)


def build_auto_block(stages):
    rows = registry.read_all()
    runs = final_runs(rows, stages)
    missing = [r['run_id'] for seeds in runs.values() for r in seeds.values() if per_task_success(r) is None]
    parts = [AUTO_BEGIN, '',
             f'_Generated {datetime.now().strftime("%Y-%m-%d %H:%M")} from `scripts/registry.csv` '
             f'({len(rows)} rows)._', '',
             goal_reaching_section(runs, stages), '', claims_section(runs), '',
             general_reward_section(rows), '', learning_curves_section(rows), '', inventory_section(rows), '']
    if missing:
        parts += [f'Warning: no local eval.csv for {", ".join(missing)} (rsync from the cluster?).', '']
    parts.append(AUTO_END)
    return '\n'.join(parts), missing


SKELETON = """# Replication results (spec 01)

## Summary

(hand-written)

## Results

{auto}

## 5. Discrepancies

(hand-written; details in `replication-log.md`)
"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--stages', default='B1,B2', help='Comma-separated registry stages for the main tables.')
    p.add_argument('--out', default=DEFAULT_OUT)
    args = p.parse_args()

    auto, missing = build_auto_block([s for s in args.stages.split(',') if s])
    if os.path.exists(args.out):
        text = open(args.out).read()
        if AUTO_BEGIN not in text or AUTO_END not in text:
            sys.exit(f'{args.out} has no AUTO markers; refusing to overwrite hand-written content.')
        head, rest = text.split(AUTO_BEGIN, 1)
        tail = rest.split(AUTO_END, 1)[1]
        text = head + auto + tail
    else:
        text = SKELETON.format(auto=auto)
    with open(args.out, 'w') as f:
        f.write(text)
    print(f'wrote {args.out}' + (f' ({len(missing)} runs without local eval.csv)' if missing else ''))


if __name__ == '__main__':
    main()
